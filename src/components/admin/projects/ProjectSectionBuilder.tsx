"use client";

import { useRef, useState } from "react";
import {
  Plus,
  Trash2,
  GripVertical,
  Eye,
  EyeOff,
  ChevronDown,
  ChevronUp,
  Upload,
  X,
} from "lucide-react";

import { createClient } from "@/lib/supabase/client";
import {
  createProjectContentBlock,
  normalizeProjectContent,
  type ProjectBlockType,
  type ProjectContentBlockUnion,
  type ProjectSectionContent,
} from "@/types/project-content";
import type { ProjectSectionPayload } from "@/app/admin/(protected)/projects/actions";

type SectionEditorData = ProjectSectionPayload & {
  localId: string;
};

type Props = {
  sections: SectionEditorData[];
  onChange: (sections: SectionEditorData[]) => void;
  projectId?: string;
};

const inputClass =
  "w-full rounded-lg border border-[#E2E8F0] bg-white px-3 py-2.5 text-sm text-[#0B1F3A] outline-none transition focus:border-[#2563EB] focus:ring-2 focus:ring-blue-100";

const secondaryButton =
  "inline-flex items-center justify-center gap-2 rounded-lg border border-[#E2E8F0] bg-white px-3 py-2 text-sm font-medium text-[#334155] transition hover:bg-slate-50";

const blockOptions: { type: ProjectBlockType; label: string }[] = [
  { type: "text", label: "Text" },
  { type: "image", label: "Image" },
  { type: "table", label: "Table" },
  { type: "metrics", label: "Metrics" },
  { type: "list", label: "List" },
  { type: "callout", label: "Callout" },
  { type: "link", label: "Link" },
];

function slugify(value: string) {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * Membuat section_key yang unik berdasarkan key section lain.
 * Jika key sudah digunakan, tambahkan suffix angka (-2, -3, dst.).
 */
function createUniqueSectionKey(
  value: string,
  sections: SectionEditorData[],
  excludeLocalId?: string
) {
  const base = slugify(value) || "section";

  const usedKeys = new Set(
    sections
      .filter((section) => section.localId !== excludeLocalId)
      .map((section) => slugify(section.section_key))
      .filter(Boolean)
  );

  if (!usedKeys.has(base)) {
    return base;
  }

  let suffix = 2;
  let candidate = `${base}-${suffix}`;

  while (usedKeys.has(candidate)) {
    suffix += 1;
    candidate = `${base}-${suffix}`;
  }

  return candidate;
}

/**
 * Memeriksa apakah section_key masih merupakan key otomatis.
 * Key yang dibuat atau diedit secara manual tidak akan otomatis
 * ditimpa ketika judul section berubah.
 */
function isAutoGeneratedSectionKey(section: SectionEditorData) {
  const currentKey = slugify(section.section_key);
  const currentTitleKey = slugify(section.title);

  if (!currentKey) {
    return true;
  }

  if (currentKey.startsWith("section-")) {
    return true;
  }

  if (!currentTitleKey) {
    return false;
  }

  if (currentKey === currentTitleKey) {
    return true;
  }

  const escapedTitleKey = currentTitleKey.replace(
    /[.*+?^${}()|[\]\\]/g,
    "\\$&"
  );

  return new RegExp(`^${escapedTitleKey}-\\d+$`).test(currentKey);
}

function createSection(
  order: number,
  sections: SectionEditorData[]
): SectionEditorData {
  return {
    localId: crypto.randomUUID(),
    section_key: createUniqueSectionKey(
      `section-${order + 1}`,
      sections
    ),
    title: "",
    subtitle: "",
    section_type: "content",
    content: [],
    display_order: order,
    is_visible: true,
  };
}

function moveItem<T>(items: T[], from: number, to: number): T[] {
  if (
    from < 0 ||
    to < 0 ||
    from >= items.length ||
    to >= items.length ||
    from === to
  ) {
    return items;
  }

  const result = [...items];
  const [moved] = result.splice(from, 1);
  result.splice(to, 0, moved);
  return result;
}

function Field({
  label,
  children,
}: {
  label: string;
  children: React.ReactNode;
}) {
  return (
    <label className="block space-y-1.5">
      <span className="text-xs font-semibold text-[#64748B]">{label}</span>
      {children}
    </label>
  );
}

export default function ProjectSectionBuilder({
  sections,
  onChange,
  projectId,
}: Props) {
  const supabase = createClient();

  const [uploadingBlockId, setUploadingBlockId] = useState<string | null>(
    null
  );

  const [uploadError, setUploadError] = useState("");

  // Menyimpan identitas section yang section_key-nya diedit manual.
  const manuallyEditedKeys = useRef<Set<string>>(new Set());

  const updateSection = (
    localId: string,
    updates: Partial<SectionEditorData>
  ) => {
    onChange(
      sections.map((section) =>
        section.localId === localId
          ? { ...section, ...updates }
          : section
      )
    );
  };

  const updateBlocks = (
    localId: string,
    blocks: ProjectSectionContent
  ) => {
    updateSection(localId, { content: blocks });
  };

  const getBlocks = (section: SectionEditorData) =>
    normalizeProjectContent(section.content);

  // Membuat section baru dengan key yang dipastikan unik.
  const addSection = () => {
    onChange([
      ...sections,
      createSection(sections.length, sections),
    ]);
  };

  const removeSection = (localId: string) => {
    manuallyEditedKeys.current.delete(localId);

    onChange(
      sections
        .filter((section) => section.localId !== localId)
        .map((section, index) => ({
          ...section,
          display_order: index,
        }))
    );
  };

  const moveSection = (from: number, to: number) => {
    onChange(
      moveItem(sections, from, to).map((section, index) => ({
        ...section,
        display_order: index,
      }))
    );
  };

  const addBlock = (
    section: SectionEditorData,
    type: ProjectBlockType
  ) => {
    const blocks = getBlocks(section);

    updateBlocks(section.localId, [
      ...blocks,
      createProjectContentBlock(type),
    ]);
  };

  const updateBlock = (
    section: SectionEditorData,
    blockId: string,
    updates: Partial<ProjectContentBlockUnion>
  ) => {
    const blocks = getBlocks(section).map((block) =>
      block.id === blockId
        ? ({ ...block, ...updates } as ProjectContentBlockUnion)
        : block
    );

    updateBlocks(section.localId, blocks);
  };

  const updateBlockData = (
    section: SectionEditorData,
    block: ProjectContentBlockUnion,
    updates: Record<string, unknown>
  ) => {
    updateBlock(section, block.id, {
      data: { ...block.data, ...updates },
    } as Partial<ProjectContentBlockUnion>);
  };

  const removeBlock = (
    section: SectionEditorData,
    blockId: string
  ) => {
    updateBlocks(
      section.localId,
      getBlocks(section).filter((block) => block.id !== blockId)
    );
  };

  const moveBlock = (
    section: SectionEditorData,
    from: number,
    to: number
  ) => {
    updateBlocks(section.localId, moveItem(getBlocks(section), from, to));
  };

  async function uploadImage(
    section: SectionEditorData,
    block: Extract<ProjectContentBlockUnion, { type: "image" }>,
    file: File
  ) {
    setUploadError("");

    const allowedTypes = ["image/jpeg", "image/png", "image/webp"];

    if (!allowedTypes.includes(file.type)) {
      setUploadError("Gambar harus berupa JPG, PNG, atau WebP.");
      return;
    }

    if (file.size > 10 * 1024 * 1024) {
      setUploadError("Ukuran gambar maksimal 10 MB.");
      return;
    }

    setUploadingBlockId(block.id);

    try {
      const extension = file.name.split(".").pop()?.toLowerCase() || "jpg";
      const folder = projectId ?? "pending";
      const path = `projects/${folder}/sections/${crypto.randomUUID()}.${extension}`;

      const { error } = await supabase.storage
        .from("portfolio-media")
        .upload(path, file, {
          cacheControl: "3600",
          upsert: false,
          contentType: file.type,
        });

      if (error) throw error;

      updateBlockData(section, block, { path });
    } catch (error) {
      setUploadError(
        error instanceof Error ? error.message : "Gagal mengunggah gambar."
      );
    } finally {
      setUploadingBlockId(null);
    }
  }

  const imageUrl = (path: string) => {
    if (!path) return "";
    if (path.startsWith("http")) return path;

    return supabase.storage.from("portfolio-media").getPublicUrl(path)
      .data.publicUrl;
  };

  return (
    <div className="space-y-5">
      <div className="flex flex-col justify-between gap-3 sm:flex-row sm:items-center">
        <div>
          <p className="text-sm text-[#64748B]">
            Susun halaman detail project menggunakan section dan berbagai
            jenis content block.
          </p>

          <p className="mt-1 text-xs text-[#94A3B8]">
            Kamu dapat mengubah urutan section maupun block dengan drag and
            drop.
          </p>
        </div>

        <button type="button" onClick={addSection} className={secondaryButton}>
          <Plus size={16} />
          Add Section
        </button>
      </div>

      {uploadError && (
        <div className="rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700">
          {uploadError}
        </div>
      )}

      {sections.length === 0 && (
        <div className="rounded-xl border-2 border-dashed border-[#CBD5E1] px-6 py-10 text-center">
          <p className="text-sm text-[#64748B]">Belum ada section.</p>

          <button
            type="button"
            onClick={addSection}
            className="mt-3 text-sm font-semibold text-[#2563EB] hover:underline"
          >
            Buat section pertama
          </button>
        </div>
      )}

      {sections.map((section, sectionIndex) => {
        const blocks = getBlocks(section);

        return (
          <section
            key={section.localId}
            draggable
            onDragStart={(event) => {
              event.dataTransfer.setData(
                "text/section-index",
                String(sectionIndex)
              );

              event.dataTransfer.effectAllowed = "move";
            }}
            onDragOver={(event) => event.preventDefault()}
            onDrop={(event) => {
              event.preventDefault();

              const from = Number(
                event.dataTransfer.getData("text/section-index")
              );

              if (Number.isInteger(from)) {
                moveSection(from, sectionIndex);
              }
            }}
            className="overflow-hidden rounded-xl border border-[#E2E8F0] bg-white"
          >
            <div className="flex items-center justify-between gap-3 border-b border-[#E2E8F0] bg-slate-50 px-4 py-3">
              <div className="flex min-w-0 items-center gap-2">
                <GripVertical
                  size={18}
                  className="shrink-0 cursor-grab text-[#94A3B8]"
                />

                <span className="truncate text-sm font-semibold text-[#0B1F3A]">
                  Section {sectionIndex + 1}
                  {section.title ? ` — ${section.title}` : ""}
                </span>
              </div>

              <div className="flex shrink-0 items-center gap-1">
                <button
                  type="button"
                  onClick={() =>
                    updateSection(section.localId, {
                      is_visible: !section.is_visible,
                    })
                  }
                  className="rounded-lg p-2 text-[#64748B] hover:bg-white"
                  title={section.is_visible ? "Hide section" : "Show section"}
                >
                  {section.is_visible ? (
                    <Eye size={16} />
                  ) : (
                    <EyeOff size={16} />
                  )}
                </button>

                <button
                  type="button"
                  onClick={() => removeSection(section.localId)}
                  className="rounded-lg p-2 text-red-600 hover:bg-red-50"
                  title="Remove section"
                >
                  <Trash2 size={16} />
                </button>
              </div>
            </div>

            <div className="space-y-5 p-4 sm:p-5">
              {!section.is_visible && (
                <p className="rounded-lg bg-amber-50 px-3 py-2 text-xs text-amber-700">
                  Section ini disembunyikan dari halaman publik.
                </p>
              )}

              <div className="grid gap-4 md:grid-cols-2">
                <Field label="Section Title">
                  <input
                    className={inputClass}
                    value={section.title}
                    onChange={(event) => {
                      const title = event.target.value;

                      const currentAutoKey = slugify(section.title);
                      const isAutoGenerated =
                        section.section_key === currentAutoKey ||
                        section.section_key === `section-${sectionIndex + 1}`;


                      updateSection(section.localId, {
                        title,
                        section_key: isAutoGenerated
                          ? slugify(title) || `section-${sectionIndex + 1}`
                          : section.section_key,
                      });
                    }}
                    placeholder="e.g. Data Preparation"
                  />
                </Field>

                <Field label="Section Key">
                  <input
                    className={inputClass}
                    value={section.section_key}
                    onChange={(event) => {
                      const inputValue = slugify(event.target.value);

                      if (inputValue) {
                        manuallyEditedKeys.current.add(section.localId);
                      } else {
                        manuallyEditedKeys.current.delete(section.localId);
                      }

                      const uniqueKey = inputValue
                        ? createUniqueSectionKey(
                            inputValue,
                            sections,
                            section.localId
                          )
                        : "";

                      updateSection(section.localId, {
                        section_key: uniqueKey,
                      });
                    }}
                    placeholder="data-preparation"
                  />
                </Field>
              </div>

              <Field label="Subtitle">
                <input
                  className={inputClass}
                  value={section.subtitle}
                  onChange={(event) =>
                    updateSection(section.localId, {
                      subtitle: event.target.value,
                    })
                  }
                  placeholder="Optional section subtitle"
                />
              </Field>

              <div className="space-y-3">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <h3 className="text-sm font-semibold text-[#0B1F3A]">
                    Content Blocks ({blocks.length})
                  </h3>

                  <div className="flex flex-wrap gap-2">
                    {blockOptions.map((option) => (
                      <button
                        key={option.type}
                        type="button"
                        onClick={() => addBlock(section, option.type)}
                        className="inline-flex items-center gap-1 rounded-lg border border-[#DBEAFE] bg-blue-50 px-2.5 py-1.5 text-xs font-medium text-[#2563EB] transition hover:bg-blue-100"
                      >
                        <Plus size={13} />
                        {option.label}
                      </button>
                    ))}
                  </div>
                </div>

                {blocks.length === 0 && (
                  <div className="rounded-lg border border-dashed border-[#CBD5E1] px-4 py-7 text-center text-sm text-[#94A3B8]">
                    Belum ada content block. Tambahkan Text, Image, Table,
                    atau jenis konten lainnya.
                  </div>
                )}

                {blocks.map((block, blockIndex) => (
                  <div
                    key={block.id}
                    draggable
                    onDragStart={(event) => {
                      event.dataTransfer.setData(
                        "text/block-index",
                        String(blockIndex)
                      );

                      event.dataTransfer.setData(
                        "text/block-section",
                        section.localId
                      );

                      event.dataTransfer.effectAllowed = "move";
                    }}
                    onDragOver={(event) => event.preventDefault()}
                    onDrop={(event) => {
                      event.preventDefault();

                      const sourceSection = event.dataTransfer.getData(
                        "text/block-section"
                      );

                      const from = Number(
                        event.dataTransfer.getData("text/block-index")
                      );

                      if (
                        sourceSection === section.localId &&
                        Number.isInteger(from)
                      ) {
                        moveBlock(section, from, blockIndex);
                      }
                    }}
                    className={`rounded-xl border p-4 ${
                      block.is_visible
                        ? "border-[#E2E8F0] bg-white"
                        : "border-amber-200 bg-amber-50/50"
                    }`}
                  >
                    <div className="mb-4 flex items-center justify-between gap-3">
                      <div className="flex items-center gap-2">
                        <GripVertical
                          size={16}
                          className="cursor-grab text-[#94A3B8]"
                        />

                        <span className="text-xs font-bold uppercase tracking-wide text-[#64748B]">
                          {block.type} block
                        </span>

                        {!block.is_visible && (
                          <span className="text-xs text-amber-700">
                            Hidden
                          </span>
                        )}
                      </div>

                      <div className="flex items-center gap-1">
                        <button
                          type="button"
                          onClick={() =>
                            updateBlock(section, block.id, {
                              is_visible: !block.is_visible,
                            })
                          }
                          className="rounded-lg p-2 text-[#64748B] hover:bg-slate-100"
                          title="Toggle visibility"
                        >
                          {block.is_visible ? (
                            <Eye size={15} />
                          ) : (
                            <EyeOff size={15} />
                          )}
                        </button>

                        <button
                          type="button"
                          onClick={() => removeBlock(section, block.id)}
                          className="rounded-lg p-2 text-red-600 hover:bg-red-50"
                          title="Remove block"
                        >
                          <Trash2 size={15} />
                        </button>
                      </div>
                    </div>

                    {block.type === "text" && (
                      <div className="space-y-3">
                        <Field label="Heading">
                          <input
                            className={inputClass}
                            value={block.data.heading ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                heading: event.target.value,
                              })
                            }
                            placeholder="Optional heading"
                          />
                        </Field>

                        <Field label="Body">
                          <textarea
                            className={inputClass}
                            rows={5}
                            value={block.data.body}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                body: event.target.value,
                              })
                            }
                            placeholder="Write your content here..."
                          />
                        </Field>
                      </div>
                    )}

                    {block.type === "image" && (
                      <div className="space-y-3">
                        {block.data.path && (
                          <div className="relative max-w-lg overflow-hidden rounded-lg border border-[#E2E8F0]">
                            <img
                              src={imageUrl(block.data.path)}
                              alt={block.data.alt || "Project image"}
                              className="max-h-72 w-full object-contain"
                            />

                            <button
                              type="button"
                              onClick={() =>
                                updateBlockData(section, block, { path: "" })
                              }
                              className="absolute right-2 top-2 rounded-lg bg-white p-2 text-red-600 shadow"
                              title="Remove image from block"
                            >
                              <X size={15} />
                            </button>
                          </div>
                        )}

                        {!block.data.path && (
                          <label className="flex cursor-pointer flex-col items-center justify-center rounded-lg border-2 border-dashed border-[#CBD5E1] bg-slate-50 px-4 py-7 text-center hover:border-[#2563EB]">
                            <Upload size={22} className="mb-2 text-[#64748B]" />

                            <span className="text-sm font-medium text-[#334155]">
                              {uploadingBlockId === block.id
                                ? "Uploading..."
                                : "Upload image"}
                            </span>

                            <span className="mt-1 text-xs text-[#94A3B8]">
                              JPG, PNG, WebP — max 10 MB
                            </span>

                            <input
                              type="file"
                              accept="image/jpeg,image/png,image/webp"
                              className="hidden"
                              disabled={uploadingBlockId === block.id}
                              onChange={(event) => {
                                const file = event.target.files?.[0];

                                if (file) {
                                  void uploadImage(section, block, file);
                                }

                                event.target.value = "";
                              }}
                            />
                          </label>
                        )}

                        <Field label="Alt Text">
                          <input
                            className={inputClass}
                            value={block.data.alt}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                alt: event.target.value,
                              })
                            }
                            placeholder="Describe the image for accessibility"
                          />
                        </Field>

                        <Field label="Caption">
                          <input
                            className={inputClass}
                            value={block.data.caption ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                caption: event.target.value,
                              })
                            }
                            placeholder="Short image caption"
                          />
                        </Field>

                        <Field label="Image Description">
                          <textarea
                            className={inputClass}
                            rows={3}
                            value={block.data.description ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                description: event.target.value,
                              })
                            }
                            placeholder="Optional explanation about this image"
                          />
                        </Field>

                        <Field label="Image Layout">
                          <select
                            className={inputClass}
                            value={block.data.layout}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                layout: event.target.value,
                              })
                            }
                          >
                            <option value="full">Full Width</option>
                            <option value="half">Half Width</option>
                            <option value="image-text">Image + Text</option>
                          </select>
                        </Field>
                      </div>
                    )}

                    {block.type === "table" && (
                      <div className="space-y-3">
                        <Field label="Table Title">
                          <input
                            className={inputClass}
                            value={block.data.title ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                title: event.target.value,
                              })
                            }
                            placeholder="Optional table title"
                          />
                        </Field>

                        <Field label="Description">
                          <textarea
                            className={inputClass}
                            rows={2}
                            value={block.data.description ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                description: event.target.value,
                              })
                            }
                          />
                        </Field>

                        <div className="space-y-2">
                          <div className="flex items-center justify-between">
                            <span className="text-xs font-semibold text-[#64748B]">
                              Columns
                            </span>

                            <button
                              type="button"
                              className="text-xs font-semibold text-[#2563EB]"
                              onClick={() =>
                                updateBlockData(section, block, {
                                  columns: [
                                    ...block.data.columns,
                                    `Column ${block.data.columns.length + 1}`,
                                  ],
                                  rows: block.data.rows.map((row) => [
                                    ...row,
                                    "",
                                  ]),
                                })
                              }
                            >
                              + Add Column
                            </button>
                          </div>

                          {block.data.columns.map((column, columnIndex) => (
                            <div key={columnIndex} className="flex gap-2">
                              <input
                                className={inputClass}
                                value={column}
                                onChange={(event) =>
                                  updateBlockData(section, block, {
                                    columns: block.data.columns.map(
                                      (item, index) =>
                                        index === columnIndex
                                          ? event.target.value
                                          : item
                                    ),
                                  })
                                }
                              />

                              <button
                                type="button"
                                disabled={block.data.columns.length <= 1}
                                onClick={() =>
                                  updateBlockData(section, block, {
                                    columns: block.data.columns.filter(
                                      (_, index) => index !== columnIndex
                                    ),
                                    rows: block.data.rows.map((row) =>
                                      row.filter(
                                        (_, index) => index !== columnIndex
                                      )
                                    ),
                                  })
                                }
                                className="rounded-lg px-2 text-red-600 disabled:opacity-30"
                              >
                                <X size={16} />
                              </button>
                            </div>
                          ))}
                        </div>

                        <div className="space-y-2">
                          <div className="flex items-center justify-between">
                            <span className="text-xs font-semibold text-[#64748B]">
                              Rows
                            </span>

                            <button
                              type="button"
                              className="text-xs font-semibold text-[#2563EB]"
                              onClick={() =>
                                updateBlockData(section, block, {
                                  rows: [
                                    ...block.data.rows,
                                    block.data.columns.map(() => ""),
                                  ],
                                })
                              }
                            >
                              + Add Row
                            </button>
                          </div>

                          {block.data.rows.map((row, rowIndex) => (
                            <div
                              key={rowIndex}
                              className="space-y-2 rounded-lg bg-slate-50 p-3"
                            >
                              <div className="flex justify-between">
                                <span className="text-xs text-[#64748B]">
                                  Row {rowIndex + 1}
                                </span>

                                <button
                                  type="button"
                                  disabled={block.data.rows.length <= 1}
                                  onClick={() =>
                                    updateBlockData(section, block, {
                                      rows: block.data.rows.filter(
                                        (_, index) => index !== rowIndex
                                      ),
                                    })
                                  }
                                  className="text-xs text-red-600 disabled:opacity-30"
                                >
                                  Remove row
                                </button>
                              </div>

                              {block.data.columns.map((_, columnIndex) => (
                                <input
                                  key={columnIndex}
                                  className={inputClass}
                                  value={row[columnIndex] ?? ""}
                                  onChange={(event) =>
                                    updateBlockData(section, block, {
                                      rows: block.data.rows.map(
                                        (currentRow, index) =>
                                          index === rowIndex
                                            ? currentRow.map((cell, cellIndex) =>
                                                cellIndex === columnIndex
                                                  ? event.target.value
                                                  : cell
                                              )
                                            : currentRow
                                      ),
                                    })
                                  }
                                  placeholder={`Column ${columnIndex + 1}`}
                                />
                              ))}
                            </div>
                          ))}
                        </div>
                      </div>
                    )}

                    {block.type === "metrics" && (
                      <div className="space-y-3">
                        <Field label="Heading">
                          <input
                            className={inputClass}
                            value={block.data.heading ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                heading: event.target.value,
                              })
                            }
                          />
                        </Field>

                        {block.data.items.map((item, index) => (
                          <div
                            key={item.id}
                            className="grid gap-2 rounded-lg bg-slate-50 p-3 md:grid-cols-2"
                          >
                            <Field label="Value">
                              <input
                                className={inputClass}
                                value={item.value}
                                onChange={(event) =>
                                  updateBlockData(section, block, {
                                    items: block.data.items.map((current, i) =>
                                      i === index
                                        ? { ...current, value: event.target.value }
                                        : current
                                    ),
                                  })
                                }
                                placeholder="e.g. 95%"
                              />
                            </Field>

                            <Field label="Label">
                              <input
                                className={inputClass}
                                value={item.label}
                                onChange={(event) =>
                                  updateBlockData(section, block, {
                                    items: block.data.items.map((current, i) =>
                                      i === index
                                        ? { ...current, label: event.target.value }
                                        : current
                                    ),
                                  })
                                }
                                placeholder="e.g. Accuracy"
                              />
                            </Field>

                            <div className="md:col-span-2">
                              <Field label="Description">
                                <input
                                  className={inputClass}
                                  value={item.description ?? ""}
                                  onChange={(event) =>
                                    updateBlockData(section, block, {
                                      items: block.data.items.map((current, i) =>
                                        i === index
                                          ? {
                                              ...current,
                                              description: event.target.value,
                                            }
                                          : current
                                      ),
                                    })
                                  }
                                />
                              </Field>
                            </div>

                            <button
                              type="button"
                              onClick={() =>
                                updateBlockData(section, block, {
                                  items: block.data.items.filter(
                                    (_, i) => i !== index
                                  ),
                                })
                              }
                              className="text-left text-xs text-red-600"
                            >
                              Remove metric
                            </button>
                          </div>
                        ))}

                        <button
                          type="button"
                          onClick={() =>
                            updateBlockData(section, block, {
                              items: [
                                ...block.data.items,
                                {
                                  id: crypto.randomUUID(),
                                  value: "",
                                  label: "",
                                  description: "",
                                },
                              ],
                            })
                          }
                          className={secondaryButton}
                        >
                          <Plus size={14} />
                          Add Metric
                        </button>
                      </div>
                    )}

                    {block.type === "list" && (
                      <div className="space-y-3">
                        <Field label="Heading">
                          <input
                            className={inputClass}
                            value={block.data.heading ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                heading: event.target.value,
                              })
                            }
                          />
                        </Field>

                        <Field label="List Style">
                          <select
                            className={inputClass}
                            value={block.data.style}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                style: event.target.value,
                              })
                            }
                          >
                            <option value="bullet">Bullet</option>
                            <option value="numbered">Numbered</option>
                          </select>
                        </Field>

                        {block.data.items.map((item, index) => (
                          <div key={index} className="flex gap-2">
                            <input
                              className={inputClass}
                              value={item}
                              onChange={(event) =>
                                updateBlockData(section, block, {
                                  items: block.data.items.map((current, i) =>
                                    i === index ? event.target.value : current
                                  ),
                                })
                              }
                              placeholder={`List item ${index + 1}`}
                            />

                            <button
                              type="button"
                              onClick={() =>
                                updateBlockData(section, block, {
                                  items: block.data.items.filter(
                                    (_, i) => i !== index
                                  ),
                                })
                              }
                              className="px-2 text-red-600"
                            >
                              <X size={16} />
                            </button>
                          </div>
                        ))}

                        <button
                          type="button"
                          onClick={() =>
                            updateBlockData(section, block, {
                              items: [...block.data.items, ""],
                            })
                          }
                          className={secondaryButton}
                        >
                          <Plus size={14} />
                          Add Item
                        </button>
                      </div>
                    )}

                    {block.type === "callout" && (
                      <div className="space-y-3">
                        <Field label="Style">
                          <select
                            className={inputClass}
                            value={block.data.variant}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                variant: event.target.value,
                              })
                            }
                          >
                            <option value="info">Information</option>
                            <option value="success">Success</option>
                            <option value="warning">Warning</option>
                            <option value="default">Default</option>
                          </select>
                        </Field>

                        <Field label="Title">
                          <input
                            className={inputClass}
                            value={block.data.title ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                title: event.target.value,
                              })
                            }
                          />
                        </Field>

                        <Field label="Message">
                          <textarea
                            className={inputClass}
                            rows={3}
                            value={block.data.message}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                message: event.target.value,
                              })
                            }
                          />
                        </Field>
                      </div>
                    )}

                    {block.type === "link" && (
                      <div className="space-y-3">
                        <Field label="Link Label">
                          <input
                            className={inputClass}
                            value={block.data.label}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                label: event.target.value,
                              })
                            }
                            placeholder="View source code"
                          />
                        </Field>

                        <Field label="URL">
                          <input
                            className={inputClass}
                            type="url"
                            value={block.data.url}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                url: event.target.value,
                              })
                            }
                            placeholder="https://..."
                          />
                        </Field>

                        <Field label="Description">
                          <textarea
                            className={inputClass}
                            rows={2}
                            value={block.data.description ?? ""}
                            onChange={(event) =>
                              updateBlockData(section, block, {
                                description: event.target.value,
                              })
                            }
                          />
                        </Field>
                      </div>
                    )}
                  </div>
                ))}
              </div>
            </div>
          </section>
        );
      })}
    </div>
  );
}